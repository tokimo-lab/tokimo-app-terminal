/** Resolve the actual xterm.js ITheme for the given terminal theme ID + current app theme. */
export function getTerminalTheme(
  terminalThemeId: TerminalThemeId,
  appTheme: "dark" | "light",
): ITheme {
  if (terminalThemeId === "auto") {
    const fallback = TERMINAL_THEMES.find(
      (t) => t.id === (appTheme === "dark" ? "dark" : "light"),
    );
    return fallback?.palette ?? {};
  }
  const def = TERMINAL_THEMES.find((t) => t.id === terminalThemeId);
  return def?.palette ?? {};
}
